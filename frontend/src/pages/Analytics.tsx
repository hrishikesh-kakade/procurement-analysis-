import { useEffect, useRef, useState } from "react";
import { Bar, BarChart, CartesianGrid, Legend, Line, LineChart, ResponsiveContainer, Tooltip, XAxis, YAxis } from "recharts";
import { api, formatError } from "../api";
import { money, percent, saveBlob } from "../format";
import { Badge, Card, Empty, ErrorText, PageHeader, Spinner, useToast } from "../ui";

const REPORTS = [
  ["supplier_performance", "Supplier performance"],
  ["supplier_scorecard", "Supplier scorecard"],
  ["monthly_spend", "Monthly spend"],
  ["department_spend", "Department spend"],
  ["purchase_orders", "Purchase orders"],
];

function ReportExport({ from, to }: { from: string; to: string }) {
  const toast = useToast();
  const [type, setType] = useState("supplier_performance");
  const [state, setState] = useState<string | null>(null);
  const timer = useRef<any>(null);
  useEffect(() => () => clearTimeout(timer.current), []);

  async function run() {
    try {
      setState("queued");
      const job = await api.post("/reports", { report_type: type, date_from: from || null, date_to: to || null });
      for (let attempt = 0; attempt < 40; attempt++) {
        const status = await api.get(`/reports/${job.job_id}`);
        setState(status.status);
        if (status.status === "finished") {
          saveBlob(await api.download(`/reports/${job.job_id}/download`), `${type}.csv`);
          toast("Report downloaded");
          return;
        }
        if (status.status === "failed") throw new Error("The report job failed");
        await new Promise((resolve) => (timer.current = setTimeout(resolve, 1000)));
      }
      throw new Error("The report is taking longer than expected — try again shortly");
    } catch (e) {
      toast(formatError(e), "err");
      setState(null);
    }
  }

  return (
    <Card title="Export a report (CSV)" actions={state && <Badge value={state} />}>
      <p className="muted" style={{ marginTop: 0 }}>Reports are generated by a background worker and respect the date range above.</p>
      <div className="row">
        <select style={{ maxWidth: 260 }} value={type} onChange={(e) => setType(e.target.value)}>{REPORTS.map(([v, l]) => <option key={v} value={v}>{l}</option>)}</select>
        <button className="btn" onClick={run} disabled={!!state && state !== "finished"}>Generate &amp; download</button>
      </div>
    </Card>
  );
}

export default function Analytics() {
  const [from, setFrom] = useState("");
  const [to, setTo] = useState("");
  const [data, setData] = useState<any>(null);
  const [error, setError] = useState<string | null>(null);

  useEffect(() => {
    setData(null);
    const params = { date_from: from, date_to: to };
    Promise.all([
      api.get("/analytics/total-spend", params),
      api.get("/analytics/monthly-spend", params),
      api.get("/analytics/department-spend", params),
      api.get("/analytics/suppliers", params),
      api.get("/analytics/supplier-scorecard", params),
    ])
      .then(([total, monthly, departments, suppliers, scorecard]) => { setError(null); setData({ total, monthly, departments, suppliers, scorecard }); })
      .catch((e) => setError(formatError(e)));
  }, [from, to]);

  return (
    <>
      <PageHeader title="Analytics" subtitle="Spend, supplier performance and trends." actions={
        <div className="row">
          <input type="date" value={from} onChange={(e) => setFrom(e.target.value)} aria-label="From date" />
          <span className="muted">to</span>
          <input type="date" value={to} onChange={(e) => setTo(e.target.value)} aria-label="To date" />
          {(from || to) && <button className="btn ghost sm" onClick={() => { setFrom(""); setTo(""); }}>Clear</button>}
        </div>
      } />
      <ErrorText error={error} />
      {!data && !error ? <Spinner /> : data && (
        <>
          <div className="grid cols-2">
            <Card title={`Monthly spend · total ${money(data.total.total_spend)} across ${data.total.order_count} orders`}>
              {data.monthly.length === 0 ? <Empty /> : (
                <ResponsiveContainer width="100%" height={280}>
                  <LineChart data={data.monthly.map((m: any) => ({ ...m, total_spend: Number(m.total_spend) }))}>
                    <CartesianGrid strokeDasharray="3 3" vertical={false} /><XAxis dataKey="month" fontSize={12} /><YAxis fontSize={12} />
                    <Tooltip formatter={(v: any) => money(v)} /><Line type="monotone" dataKey="total_spend" name="Spend" stroke="#4f46e5" strokeWidth={2.5} dot />
                  </LineChart>
                </ResponsiveContainer>
              )}
            </Card>
            <Card title="Department spend">
              {data.departments.length === 0 ? <Empty /> : (
                <ResponsiveContainer width="100%" height={280}>
                  <BarChart data={data.departments.map((d: any) => ({ ...d, total_spend: Number(d.total_spend) }))} layout="vertical" margin={{ left: 24 }}>
                    <CartesianGrid strokeDasharray="3 3" horizontal={false} /><XAxis type="number" fontSize={12} /><YAxis type="category" dataKey="department" fontSize={12} width={100} />
                    <Tooltip formatter={(v: any) => money(v)} /><Bar dataKey="total_spend" name="Spend" fill="#0f9d6b" radius={[0, 6, 6, 0]} />
                  </BarChart>
                </ResponsiveContainer>
              )}
            </Card>
          </div>

          <Card title="Supplier scorecard" actions={<span className="muted">Fulfilment 40% · On-time 40% · RFQ win rate 20%</span>}>
            {data.scorecard.length === 0 ? <Empty /> : (
              <div className="table-wrap"><table>
                <thead><tr><th>Supplier</th><th className="num">Orders</th><th className="num">Spend</th><th className="num">Fulfilment</th><th className="num">On-time</th><th className="num">RFQ wins</th><th className="num">Score</th><th>Rating</th></tr></thead>
                <tbody>{data.scorecard.map((s: any) => (
                  <tr key={s.supplier_id}><td><strong>{s.supplier_name}</strong></td><td className="num">{s.order_count}</td><td className="num">{money(s.total_spend)}</td><td className="num">{percent(s.fulfillment_rate_percent)}</td><td className="num">{percent(s.on_time_delivery_rate_percent)}</td><td className="num">{percent(s.quotation_win_rate_percent)}</td><td className="num"><strong>{s.score ?? "—"}</strong></td><td><Badge value={s.rating} /></td></tr>
                ))}</tbody>
              </table></div>
            )}
          </Card>

          <Card title="Spend by supplier">
            {data.suppliers.length === 0 ? <Empty /> : (
              <ResponsiveContainer width="100%" height={Math.max(220, data.suppliers.length * 38)}>
                <BarChart data={data.suppliers.map((s: any) => ({ ...s, total_spend: Number(s.total_spend), average_po_value: Number(s.average_po_value) }))} layout="vertical" margin={{ left: 40 }}>
                  <CartesianGrid strokeDasharray="3 3" horizontal={false} /><XAxis type="number" fontSize={12} /><YAxis type="category" dataKey="supplier_name" width={150} fontSize={12} />
                  <Tooltip formatter={(v: any) => money(v)} /><Legend /><Bar dataKey="total_spend" name="Total spend" fill="#4f46e5" radius={[0, 6, 6, 0]} /><Bar dataKey="average_po_value" name="Average order" fill="#e0a21a" radius={[0, 6, 6, 0]} />
                </BarChart>
              </ResponsiveContainer>
            )}
          </Card>
          <ReportExport from={from} to={to} />
        </>
      )}
    </>
  );
}
